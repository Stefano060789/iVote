-- Repeat-visit recognition (opt-in only, voting itself stays anonymous) and
-- public review lever: review-claim reminders and pulled-in public reputation.
-- Run after 20260909_feedback_benefits.sql.

alter table public.workspaces
  add column if not exists google_place_id text;

-- Cross-poll visit recognition, keyed only by an email the voter chose to leave.
-- This never requires an account: a voter who never opts in never appears here.
create table if not exists public.voter_profiles (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  email text not null check (char_length(email) <= 320),
  visit_count int not null default 1,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  winback_sent_at timestamptz,
  unique (workspace_id, email)
);

create index if not exists idx_voter_profiles_workspace on public.voter_profiles (workspace_id);

alter table public.voter_profiles enable row level security;

drop policy if exists "managers can view voter profiles" on public.voter_profiles;
create policy "managers can view voter profiles" on public.voter_profiles
for select to authenticated using (public.is_workspace_manager(workspace_id));

