-- Public review lever: let a voter optionally leave the same opt-in email so the
-- workspace can send a single reminder if they never followed up on a claim.
alter table public.review_benefit_claims
  add column if not exists contact_email text,
  add column if not exists reminder_sent_at timestamptz;

drop function if exists public.create_review_benefit_claim(bigint, text[]);

create or replace function public.create_review_benefit_claim(
  target_poll_id bigint,
  selected_answers text[],
  contact_email text default null
)
returns table(claim_token uuid, status text)
language plpgsql
security definer
set search_path = public
as $$
declare
  target_workspace_id uuid;
  target_triggers text[];
  new_token uuid;
  normalized_email text := nullif(lower(trim(coalesce(contact_email, ''))), '');
begin
  select workspace_id, review_trigger_answers
    into target_workspace_id, target_triggers
  from public.polls
  where id = target_poll_id;

  if target_workspace_id is null then
    raise exception 'The poll does not exist.';
  end if;

  if coalesce(array_length(target_triggers, 1), 0) = 0
    or not exists (
      select 1 from unnest(coalesce(selected_answers, '{}')) answer
      where answer = any(target_triggers)
    ) then
    raise exception 'This vote is not eligible for an external review benefit.';
  end if;

  if normalized_email is not null and normalized_email !~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' then
    normalized_email := null;
  end if;

  insert into public.review_benefit_claims (workspace_id, poll_id, selected_answers, contact_email)
  values (target_workspace_id, target_poll_id, coalesce(selected_answers, '{}'), normalized_email)
  returning review_benefit_claims.claim_token into new_token;

  return query select new_token, 'pending'::text;
end;
$$;

grant execute on function public.create_review_benefit_claim(bigint, text[], text) to anon, authenticated;

-- Public reputation pulled in from Google (rating/review count over time).
create table if not exists public.reputation_snapshots (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  source text not null default 'google' check (source in ('google')),
  rating numeric,
  rating_count int,
  captured_at timestamptz not null default now()
);

create index if not exists idx_reputation_snapshots_workspace on public.reputation_snapshots (workspace_id, captured_at desc);

alter table public.reputation_snapshots enable row level security;

drop policy if exists "managers can view reputation snapshots" on public.reputation_snapshots;
create policy "managers can view reputation snapshots" on public.reputation_snapshots
for select to authenticated using (public.is_workspace_manager(workspace_id));
