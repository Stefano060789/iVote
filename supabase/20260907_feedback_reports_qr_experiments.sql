create or replace function public.validate_feedback_workspace_links()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_table_name = 'feedback_alert_rules' and not exists (
    select 1 from public.polls where id = new.poll_id and workspace_id = new.workspace_id
  ) then
    raise exception 'The alert rule poll must belong to the workspace.';
  end if;
  if tg_table_name = 'feedback_recovery_tasks' and new.alert_id is not null and not exists (
    select 1 from public.feedback_alerts where id = new.alert_id and workspace_id = new.workspace_id
  ) then
    raise exception 'The recovery task alert must belong to the workspace.';
  end if;
  return new;
end;
$$;

create trigger feedback_alert_rules_validate_workspace_links
before insert or update on public.feedback_alert_rules
for each row execute procedure public.validate_feedback_workspace_links();
create trigger feedback_recovery_tasks_validate_workspace_links
before insert or update on public.feedback_recovery_tasks
for each row execute procedure public.validate_feedback_workspace_links();

create or replace function public.create_feedback_alerts_for_vote()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.feedback_alerts (workspace_id, poll_id, rule_id, vote_id, answer)
  select new.workspace_id, new.poll_id, rule.id, new.id, new.answer
  from public.feedback_alert_rules rule
  where rule.workspace_id = new.workspace_id and rule.poll_id = new.poll_id and rule.is_enabled
    and ((rule.trigger_type = 'answer_match' and lower(trim(new.answer)) = lower(trim(rule.answer_match)))
      or (rule.trigger_type = 'low_score' and trim(new.answer) ~ '^[0-9]+(\.[0-9]+)?$' and trim(new.answer)::numeric <= rule.score_threshold));
  return new;
end;
$$;

drop trigger if exists votes_create_feedback_alerts on public.votes;
create trigger votes_create_feedback_alerts
after insert on public.votes for each row execute procedure public.create_feedback_alerts_for_vote();