alter table public.qr_campaigns add column if not exists placement_label text
  check (placement_label is null or char_length(trim(placement_label)) between 1 and 80);
alter table public.qr_campaigns add column if not exists variant_label text
  check (variant_label is null or char_length(trim(variant_label)) between 1 and 80);

create table if not exists public.feedback_alert_rules (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null default public.current_workspace_id() references public.workspaces(id) on delete cascade,
  poll_id bigint not null references public.polls(id) on delete cascade,
  trigger_type text not null check (trigger_type in ('low_score', 'answer_match')),
  score_threshold numeric check (score_threshold between 0 and 10),
  answer_match text check (char_length(trim(answer_match)) between 1 and 1000),
  is_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  check ((trigger_type = 'low_score' and score_threshold is not null and answer_match is null)
      or (trigger_type = 'answer_match' and answer_match is not null and score_threshold is null))
);

create table if not exists public.feedback_alerts (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  poll_id bigint not null references public.polls(id) on delete cascade,
  rule_id bigint references public.feedback_alert_rules(id) on delete set null,
  vote_id bigint references public.votes(id) on delete set null,
  answer text not null,
  status text not null default 'open' check (status in ('open', 'acknowledged', 'resolved')),
  created_at timestamptz not null default now(),
  unique (rule_id, vote_id)
);

create table if not exists public.feedback_recovery_tasks (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  alert_id bigint references public.feedback_alerts(id) on delete set null,
  title text not null check (char_length(trim(title)) between 1 and 240),
  status text not null default 'open' check (status in ('open', 'in_progress', 'done')),
  due_at timestamptz,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.weekly_report_settings (
  workspace_id uuid primary key references public.workspaces(id) on delete cascade,
  recipient_email text not null check (char_length(recipient_email) <= 320 and recipient_email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  is_enabled boolean not null default false,
  updated_at timestamptz not null default now()
);

create index if not exists idx_feedback_alert_rules_workspace_poll on public.feedback_alert_rules(workspace_id, poll_id);
create index if not exists idx_feedback_alerts_workspace_status on public.feedback_alerts(workspace_id, status, created_at desc);
create index if not exists idx_feedback_recovery_tasks_workspace_status on public.feedback_recovery_tasks(workspace_id, status, due_at);

alter table public.feedback_alert_rules enable row level security;
alter table public.feedback_alerts enable row level security;
alter table public.feedback_recovery_tasks enable row level security;
alter table public.weekly_report_settings enable row level security;

